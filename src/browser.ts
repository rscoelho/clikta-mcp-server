import { chromium, type Browser, type Page } from "playwright";
import { HEADLESS } from "./config.js";

// One browser/page reused across tool calls for the lifetime of this MCP
// server process — tools are stateless function calls, so the "current
// page" has to live somewhere between them.
let browser: Browser | null = null;
let page: Page | null = null;

export async function getPage(): Promise<Page> {
  // If Chromium died or its window was closed, `browser` would stay set and
  // every later call would fail with "browser.newContext: Target page,
  // context or browser has been closed" until the MCP process restarts.
  if (browser && !browser.isConnected()) {
    browser = null;
    page = null;
  }
  if (!browser) {
    browser = await chromium.launch({ headless: HEADLESS });
    browser.on("disconnected", () => {
      browser = null;
      page = null;
    });
  }
  if (!page || page.isClosed()) {
    // Matches the extension's CAPTURE_SCREENSHOT target viewport so demos
    // generated by the agent look the same as ones recorded by a human.
    const context = await browser.newContext({ viewport: { width: 1424, height: 893 } });
    page = await context.newPage();
  }
  return page;
}

export async function closeBrowser(): Promise<void> {
  await page
    ?.context()
    .close()
    .catch(() => {});
  await browser?.close().catch(() => {});
  browser = null;
  page = null;
}

export async function screenshotJpegBase64(target: Page): Promise<string> {
  const buffer = await target.screenshot({ type: "jpeg", quality: 72 });
  return buffer.toString("base64");
}
